import { useMemo, useState, type ChangeEvent } from 'react'
import { useLiveQuery } from 'dexie-react-hooks'
import { Link } from 'react-router-dom'
import { BookOpen, Download, FlaskConical, Plus, Trash2, Upload } from 'lucide-react'
import { Button, Card, EmptyState, Skeleton, useToast } from '../components/ui'
import { db, describeDbError } from '../db/db'
import { downloadText } from '../download'
import { localDate } from '../learning/dates'
import { seededRng } from '../practice/engine'
import { normalize } from '../questions/schema'
import ContentItemView from '../components/ContentItemView'
import { KIND_LABEL, QUIZ_KINDS, type ContentItem, type ContentKind } from '../content/schema'
import {
  addToRevision,
  commitContentImport,
  contentToJson,
  itemOfDay,
  loadContent,
  loadDevContent,
  loadStarterContent,
  previewContentImport,
  quizOptions,
  removeDevContent,
  removeStarterContent,
  type ContentPreview,
} from '../content/repo'

const TABS: { id: string; label: string; kinds: ContentKind[] }[] = [
  { id: 'english', label: 'English', kinds: ['word', 'idiom', 'ows', 'grammar'] },
  { id: 'polity', label: 'Indian Polity', kinds: ['polity'] },
  { id: 'ca', label: 'Current affairs', kinds: ['current-affairs'] },
  { id: 'ga', label: 'GA facts', kinds: ['ga-fact'] },
]
const field = 'min-h-11 rounded-md border border-border bg-surface px-3 text-sm'

export default function Content() {
  const toast = useToast()
  const data = useLiveQuery(loadContent)
  const inRevision = useLiveQuery(async () => new Set((await db.revisionItems.where('kind').equals('card').toArray()).map((r) => String(r.refId))))
  const [tab, setTab] = useState(TABS[0]!)
  const [kind, setKind] = useState<ContentKind | ''>('')
  const [search, setSearch] = useState('')
  const [quiz, setQuiz] = useState<ContentKind | null>(null)

  const items = useMemo(() => {
    const term = normalize(search)
    return (data?.items ?? [])
      .filter((c) => tab.kinds.includes(c.kind) && (!kind || c.kind === kind))
      .filter((c) => !term || normalize(`${c.front} ${c.back} ${c.tags.join(' ')}`).includes(term))
      .sort((a, b) => (a.kind === 'current-affairs' ? (b.publishedOn ?? '').localeCompare(a.publishedOn ?? '') : a.front.localeCompare(b.front)))
  }, [data, tab, kind, search])

  if (!data || !inRevision) return <Skeleton className="h-96 w-full" />
  const all = data.items
  const word = itemOfDay(all.filter((c) => c.kind === 'word'), localDate())
  const hasDev = all.some((c) => c.pack === 'dev-sample')
  const starterCount = all.filter((c) => c.pack === 'starter').length
  const safe = (fn: () => Promise<string>) =>
    fn().then(toast, (e) => toast(e instanceof Error && e.message.startsWith('Could not download') ? e.message : describeDbError(e)))

  return (
    <section>
      <h1 className="text-2xl font-semibold">Study content</h1>
      <p className="mt-1 max-w-2xl text-sm text-muted">
        Vocabulary, idioms, one-word substitution, grammar, Indian Polity, current affairs and GA facts from content packs you import.
        Nothing here is generated by the app. Add items to <Link className="text-accent underline" to="/revision">Revision</Link> to review
        them with spaced repetition.
      </p>

      <Card className="mt-4 flex flex-wrap items-center justify-between gap-4 border-accent">
        <div className="max-w-2xl">
          <h2 className="font-semibold">Starter study pack</h2>
          <p className="mt-1 text-sm text-muted">
            About 700 entries: vocabulary with synonyms and antonyms, idioms, one-word substitutions, grammar rules, 57 Constitution articles
            (simplified, not the constitutional text), GA facts and dated current affairs with their sources. Written by Claude; not
            expert-reviewed.
          </p>
          {starterCount > 0 && <p className="mt-1 text-sm font-medium text-success">{starterCount} starter entries loaded</p>}
        </div>
        {starterCount > 0 ? (
          <Button variant="ghost" onClick={() => safe(async () => `Removed ${await removeStarterContent()} starter entries`)}>
            <Trash2 size={16} aria-hidden /> Remove starter pack
          </Button>
        ) : (
          <Button onClick={() => safe(async () => `Added ${(await loadStarterContent()).added} entries`)}>
            <BookOpen size={16} aria-hidden /> Load starter pack
          </Button>
        )}
      </Card>

      <div role="tablist" aria-label="Content area" className="mt-4 flex gap-2 overflow-x-auto">
        {TABS.map((t) => (
          <button
            key={t.id}
            role="tab"
            type="button"
            aria-selected={tab.id === t.id}
            onClick={() => (setTab(t), setKind(''), setQuiz(null))}
            className={`min-h-11 shrink-0 rounded-md border px-3 text-sm font-medium ${tab.id === t.id ? 'border-accent bg-accent-soft text-accent' : 'border-border bg-surface text-muted'}`}
          >
            {t.label} ({all.filter((c) => t.kinds.includes(c.kind)).length})
          </button>
        ))}
      </div>

      {tab.id === 'english' && word && (
        <Card className="mt-4 border-accent">
          <p className="text-xs font-medium uppercase tracking-wide text-accent">Word of the day</p>
          <ContentItemView c={word} />
        </Card>
      )}
      {tab.id === 'ca' && (
        <p className="mt-4 rounded-md border border-warning px-4 py-2 text-sm text-warning">
          Current affairs are not updated automatically. Each item shows its publication date and source: check that it is still current.
        </p>
      )}
      {tab.id === 'polity' && (
        <p className="mt-4 text-sm text-muted">Each item says whether it is the constitutional text or a simplified explanation.</p>
      )}

      <div className="mt-4 flex flex-wrap gap-2">
        <input className={`${field} min-w-48 flex-1`} placeholder="Search" aria-label="Search content" value={search} onChange={(e) => setSearch(e.target.value)} />
        {tab.kinds.length > 1 && (
          <select className={field} aria-label="Type" value={kind} onChange={(e) => setKind(e.target.value as ContentKind | '')}>
            <option value="">All types</option>
            {tab.kinds.map((k) => (
              <option key={k} value={k}>
                {KIND_LABEL[k]}
              </option>
            ))}
          </select>
        )}
        {tab.kinds.filter((k) => QUIZ_KINDS.includes(k)).map((k) => (
          <Button key={k} variant="secondary" disabled={all.filter((c) => c.kind === k).length < 4} onClick={() => setQuiz(k)}>
            Quiz: {KIND_LABEL[k]}
          </Button>
        ))}
        <Button variant="secondary" disabled={!items.length} onClick={() => safe(async () => `Added ${await addToRevision(items.map((c) => c.id))} to revision`)}>
          <Plus size={16} aria-hidden /> Add shown to revision
        </Button>
      </div>

      {quiz && <Quiz kind={quiz} pool={all} onClose={() => setQuiz(null)} />}

      {items.length === 0 ? (
        <div className="mt-4">
          <EmptyState icon={<BookOpen size={28} aria-hidden />} title="No content here yet">
            Import a reviewed content pack below{tab.id === 'english' || tab.id === 'polity' ? ', or load the development sample to try it' : ''}.
          </EmptyState>
        </div>
      ) : (
        <ul className="mt-4 grid gap-3 md:grid-cols-2">
          {items.map((c) => (
            <li key={c.id}>
              <Card className="h-full p-4">
                <ContentItemView c={c} />
                <Button
                  variant="ghost"
                  className="mt-2"
                  disabled={inRevision.has(c.id)}
                  onClick={() => safe(async () => ((await addToRevision([c.id])) ? 'Added to revision' : 'Already in revision'))}
                >
                  {inRevision.has(c.id) ? 'In revision' : 'Add to revision'}
                </Button>
              </Card>
            </li>
          ))}
        </ul>
      )}

      <div className="mt-6 grid gap-4 lg:grid-cols-2">
        <ContentImport />
        <Card>
          <h2 className="font-semibold">Export and sample data</h2>
          <Button variant="secondary" className="mt-3" disabled={!all.length} onClick={() => downloadText(`content-${localDate()}.json`, contentToJson(all))}>
            <Download size={16} aria-hidden /> Export all as JSON ({all.length})
          </Button>
          <p className="mt-3 text-sm text-muted">
            The development sample has a few English and Polity entries written for testing, labelled DEV SAMPLE. It contains no current
            affairs.
          </p>
          <div className="mt-2">
            {hasDev ? (
              <Button variant="ghost" onClick={() => safe(async () => `Removed ${await removeDevContent()} sample items`)}>
                <Trash2 size={16} aria-hidden /> Remove development sample
              </Button>
            ) : (
              <Button variant="secondary" onClick={() => safe(async () => `Added ${await loadDevContent()} sample items`)}>
                <FlaskConical size={16} aria-hidden /> Load development sample
              </Button>
            )}
          </div>
          {data.malformed > 0 && <p className="mt-2 text-sm text-danger">{data.malformed} stored items are malformed and hidden.</p>}
        </Card>
      </div>
    </section>
  )
}

/** A short quiz built only from stored answers: the right one plus three other entries of the same kind. */
function Quiz({ kind, pool, onClose }: { kind: ContentKind; pool: ContentItem[]; onClose: () => void }) {
  const [seed] = useState(() => Date.now())
  const questions = useMemo(() => {
    const rng = seededRng(seed)
    return pool
      .filter((c) => c.kind === kind)
      .map((c) => ({ c, r: rng() }))
      .sort((a, b) => a.r - b.r)
      .slice(0, 5)
      .map(({ c }) => ({ c, options: quizOptions(c, pool, rng) }))
      .filter((q): q is { c: ContentItem; options: string[] } => !!q.options)
  }, [kind, pool, seed])
  const [i, setI] = useState(0)
  const [picked, setPicked] = useState<string | null>(null)
  const [score, setScore] = useState(0)
  const q = questions[i]
  const prompt = (c: ContentItem) => (kind === 'ows' ? `One word for: ${c.front}` : `Meaning of “${c.front}”`)

  return (
    <Card className="mt-4 border-accent">
      <div className="flex items-center justify-between gap-2">
        <h2 className="font-semibold">Quiz: {KIND_LABEL[kind]}</h2>
        <Button variant="ghost" onClick={onClose}>
          Close
        </Button>
      </div>
      {!q ? (
        <p className="mt-2 text-sm" role="status">
          Quiz finished: {score} of {questions.length} correct.
        </p>
      ) : (
        <>
          <p className="mt-2 text-xs text-muted">
            Question {i + 1} of {questions.length}
          </p>
          <p className="mt-1 font-medium">{prompt(q.c)}</p>
          <div className="mt-3 space-y-2">
            {q.options.map((o) => {
              const right = picked && o === q.c.back
              const wrong = picked === o && o !== q.c.back
              return (
                <button
                  key={o}
                  type="button"
                  disabled={!!picked}
                  onClick={() => {
                    setPicked(o)
                    if (o === q.c.back) setScore((s) => s + 1)
                  }}
                  className={`flex min-h-11 w-full items-center justify-between rounded-md border px-3 text-left text-sm ${right ? 'border-success' : wrong ? 'border-danger' : 'border-border'}`}
                >
                  {o}
                  {right && <span className="text-xs font-semibold text-success">Correct answer</span>}
                  {wrong && <span className="text-xs font-semibold text-danger">Your answer</span>}
                </button>
              )
            })}
          </div>
          {picked && (
            <Button className="mt-3" onClick={() => (setI((x) => x + 1), setPicked(null))}>
              Next
            </Button>
          )}
        </>
      )}
    </Card>
  )
}

function ContentImport() {
  const toast = useToast()
  const [preview, setPreview] = useState<ContentPreview | null>(null)
  const [mode, setMode] = useState<'skip-existing' | 'update-existing'>('skip-existing')
  const [message, setMessage] = useState('')

  async function pick(e: ChangeEvent<HTMLInputElement>) {
    const f = e.target.files?.[0]
    e.target.value = ''
    setMessage('')
    if (!f) return
    if (f.size > 10 * 1024 * 1024) return setMessage('File is larger than 10 MB.')
    try {
      setPreview(await previewContentImport(f.name, await f.text()))
    } catch (err) {
      setMessage(describeDbError(err))
    }
  }

  const rows = preview?.rows ?? []
  const n = (k: string) => rows.filter((r) => r.kind === k).length
  const toImport = n('new') + (mode === 'update-existing' ? n('existing') : 0)

  return (
    <Card>
      <h2 className="font-semibold">Import a content pack</h2>
      <p className="mt-1 text-sm text-muted">JSON or CSV, see docs/CONTENT.md. Nothing is saved until you confirm.</p>
      <label className="mt-3 inline-flex min-h-11 cursor-pointer items-center gap-2 rounded-md border border-border bg-surface px-4 text-sm font-medium hover:bg-surface-2 focus-within:outline focus-within:outline-2 focus-within:outline-accent">
        <Upload size={16} aria-hidden /> Choose file
        <input type="file" accept=".json,.csv,application/json,text/csv" className="sr-only" onChange={pick} />
      </label>
      {message && (
        <p role="status" className="mt-3 text-sm">
          {message}
        </p>
      )}
      {preview && (
        <div className="mt-3 rounded-md border border-border p-3 text-sm">
          {preview.fileErrors.map((e) => (
            <p key={e} role="alert" className="text-danger">
              {e}
            </p>
          ))}
          {!preview.fileErrors.length && (
            <>
              <p>
                New {n('new')} · already stored {n('existing')} · rejected {n('error')}
              </p>
              {n('existing') > 0 && (
                <label className="mt-2 flex min-h-11 items-center gap-2">
                  <input type="checkbox" checked={mode === 'update-existing'} onChange={(e) => setMode(e.target.checked ? 'update-existing' : 'skip-existing')} />
                  Update entries that are already stored
                </label>
              )}
              <ul className="mt-2 max-h-48 overflow-auto text-xs">
                {rows
                  .filter((r) => r.errors.length)
                  .slice(0, 100)
                  .map((r) => (
                    <li key={r.line} className="text-danger">
                      Line {r.line} {r.id && `(${r.id})`}: {r.errors.join('; ')}
                    </li>
                  ))}
              </ul>
            </>
          )}
          <div className="mt-3 flex gap-2">
            <Button
              disabled={!toImport}
              onClick={async () => {
                const r = await commitContentImport(preview, mode)
                setPreview(null)
                setMessage(`Imported ${r.added} new, updated ${r.updated}, skipped ${r.skipped}, rejected ${r.rejected}.`)
                toast('Import finished')
              }}
            >
              Import {toImport}
            </Button>
            <Button variant="ghost" onClick={() => setPreview(null)}>
              Cancel
            </Button>
          </div>
        </div>
      )}
    </Card>
  )
}
